import argparse
import csv

from utils import load_csv, predict, student_features

parser = argparse.ArgumentParser(description="Predict Hogwarts houses from a student CSV and trained weights. Writes houses.csv.")
parser.add_argument("dataset", help="Path to the student CSV to classify")
parser.add_argument("weights", help="Path to the weights.csv generated by logreg_train.py")
args = parser.parse_args()
try:
	rows = load_csv(args.dataset)
except FileNotFoundError:
	parser.error(f"File {args.dataset} not found.")

weights = {}
means = []
stds = []
with open(args.weights) as f:
	reader = csv.reader(f)
	next(reader)
	for line in reader:
		name = line[0]# "Gryffindor", "mean", "std"...
		values = [float(v) for v in line[1:]]
		if name == "mean":
			means = values
		elif name == "std":
			stds = values
		else:
			weights[name] = values

HOUSES = ["Gryffindor", "Hufflepuff", "Ravenclaw", "Slytherin"]
with open("houses.csv", "w", newline="") as f:
	writer = csv.writer(f)
	writer.writerow(["Index", "Hogwarts House"])
	for i in range(len(rows)):
		x = student_features(rows[i], means, stds)
		best_house = None
		best_proba = -1
		for house in HOUSES:
			p = predict(x, weights[house])
			if p > best_proba:
				best_proba = p
				best_house = house
		writer.writerow([int(rows[i]["Index"]), best_house])

import argparse
import csv
import sys

from utils import load_csv, predict, student_features

parser = argparse.ArgumentParser(description="Predict Hogwarts houses from a student CSV and trained weights. Writes houses.csv.")
parser.add_argument("dataset", help="Path to the student CSV to classify")
parser.add_argument("weights", help="Path to the weights.csv generated by logreg_train.py")
parser.add_argument("--visualize", action="store_true", help="Show live predictions and keep the window open when finished")
args = parser.parse_args()
try:
	rows = load_csv(args.dataset)
except FileNotFoundError:
	parser.error(f"File {args.dataset} not found.")

weights = {}
means = []
stds = []
try:
	with open(sys.argv[2]) as f:
		reader = csv.reader(f)
		next(reader)
		for line in reader:
			name = line[0]# "Gryffindor", "mean", "std"...
			values = [float(v) for v in line[1:]]
			if name == "mean":
				means = values
			elif name == "std":
				stds = values
			else:
				weights[name] = values
except FileNotFoundError:
	print(f"File {sys.argv[2]} not found.")
	sys.exit(1)

HOUSES = ["Gryffindor", "Hufflepuff", "Ravenclaw", "Slytherin"]
view = None
if args.visualize:
	try:
		from prediction_view import PredictionView
		view = PredictionView(HOUSES, len(rows))
	except (ImportError, RuntimeError) as error:
		parser.error(f"Could not open the prediction window: {error}")

with open("houses.csv", "w", newline="") as f:
	writer = csv.writer(f)
	writer.writerow(["Index", "Hogwarts House"])
	for i in range(len(rows)):
		x = student_features(rows[i], means, stds)
		best_house = None
		best_proba = -1
		for house in HOUSES:
			p = predict(x, weights[house])
			if p > best_proba:
				best_proba = p
				best_house = house
		student_index = int(rows[i]["Index"])
		writer.writerow([student_index, best_house])
		if view is not None:
			view.record(student_index, best_house)

if view is not None:
	view.finish()
